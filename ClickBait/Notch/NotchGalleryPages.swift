// MARK: Clipboard

/// What was copied this session, newest first (text and pictures), in memory only: never what
/// apps mark as secret (password managers' concealed or transient copies).
@MainActor @Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    /// One copy: text, a picture (saved beside the list), or files (their paths).
    struct Entry: Identifiable, Codable, Equatable {
        var id = UUID()
        var text: String?
        var picture: String?
        var files: [String] = []
        var at: Date
        var pinned = false
    }

    private(set) var entries: [Entry] = []
    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    private static let secret: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    /// Kept between launches, on this Mac only (user's ask, 2026-11-02): the list, and each picture.
    private static let folder = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        .appending(path: "ClickBait/Clipboard")
    private static let keep = 50

    private init() {
        if let data = try? Data(contentsOf: Self.folder.appending(path: "history.json")),
           let saved = try? JSONDecoder().decode([Entry].self, from: data) { entries = saved }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    func image(of entry: Entry) -> NSImage? { entry.picture.flatMap { NSImage(contentsOf: Self.folder.appending(path: $0)) } }

    /// Copies an entry back — text as plain text (no formatting) — and it becomes the newest.
    func copy(_ entry: Entry) {
        let board = NSPasteboard.general
        board.clearContents()
        if let image = image(of: entry) {
            board.writeObjects([image])
        } else if !entry.files.isEmpty {
            board.writeObjects(entry.files.map { URL(fileURLWithPath: $0) as NSURL })
        } else if let text = entry.text {
            board.setString(text, forType: .string)
        }
    }

    func togglePin(_ entry: Entry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].pinned.toggle()
        save()
    }

    /// One entry gone, its picture too (user's ask, 2026-11-04: not only all at once).
    func remove(_ entry: Entry) {
        remove(picture: entry)
        entries.removeAll { $0.id == entry.id }
        save()
    }

    /// Everything but the pinned ones, pictures and all.
    func clear() {
        for entry in entries where !entry.pinned { remove(picture: entry) }
        entries.removeAll { !$0.pinned }
        save()
    }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secret) else { return }
        var entry: Entry?
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            entry = Entry(text: urls.map(\.lastPathComponent).joined(separator: ", "), files: urls.map(\.path), at: Date())
        } else if var text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            // A link loses its tracking, on the clipboard too (user's choice, after Vorssaint's).
            if let clean = LinkCleaner.clean(text) {
                text = clean
                board.clearContents()
                board.setString(clean, forType: .string)
                changeCount = board.changeCount
            }
            entry = Entry(text: String(text.prefix(2000)), at: Date())
        } else if let image = NSImage(pasteboard: board), let png = Self.png(image) {
            let name = "\(UUID().uuidString).png"
            try? FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
            if (try? png.write(to: Self.folder.appending(path: name))) != nil { entry = Entry(picture: name, at: Date()) }
        }
        guard let entry else { return }
        let pinned = entries.first { $0.text != nil && $0.text == entry.text }?.pinned ?? false
        for old in entries where old.text != nil && old.text == entry.text { remove(picture: old) }
        entries.removeAll { $0.text != nil && $0.text == entry.text }
        var fresh = entry
        fresh.pinned = pinned
        entries.insert(fresh, at: 0)
        // The newest 50, pinned ones always kept.
        var unpinned = 0
        entries = entries.filter { entry in
            if entry.pinned { return true }
            unpinned += 1
            if unpinned > Self.keep { remove(picture: entry); return false }
            return true
        }
        save()
    }

    private func remove(picture entry: Entry) {
        if let name = entry.picture { try? FileManager.default.removeItem(at: Self.folder.appending(path: name)) }
    }

    private func save() {
        try? FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
        try? JSONEncoder().encode(entries).write(to: Self.folder.appending(path: "history.json"), options: .atomic)
    }

    private static func png(_ image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}

/// The clipboard: pinned first, then the newest; a click copies one back (text as plain text),
/// 📌 keeps one. Kept between launches; Clear empties all but the pinned.
struct ClipboardPage: View {
    @Bindable var history = ClipboardHistory.shared
    @State private var copied: UUID?

    /// All of it, pinned first, in a list that scrolls (user's report, 2026-11-04: only six showed,
    /// and Clear fell off the bottom).
    private var shown: [ClipboardHistory.Entry] {
        history.entries.filter(\.pinned) + history.entries.filter { !$0.pinned }
    }

    var body: some View {
        Group {
            if history.entries.isEmpty {
                EmptyPage(symbol: "doc.on.clipboard", text: "What you copy shows up here, kept on this Mac. Links lose their tracking.")
            } else {
                VStack(alignment: .leading, spacing: 8) {
                    // At the top, so it's always there however long the list.
                    HStack(spacing: 12) {
                        Text("\(history.entries.count) copied · click one to copy it as plain text").foregroundStyle(NotchPalette.tertiary)
                        Spacer()
                        Button("Clear") { history.clear() }.buttonStyle(.plain).foregroundStyle(NotchPalette.secondary)
                            .help("Everything but the pinned ones")
                    }
                    .font(.system(size: 11))
                    ScrollView(.vertical, showsIndicators: true) {
                        VStack(spacing: 4) { ForEach(shown) { entry in row(entry) } }
                    }
                    .frame(maxHeight: 220)
                }
            }
        }
        .foregroundStyle(NotchPalette.text)
    }

    private func row(_ entry: ClipboardHistory.Entry) -> some View {
        HStack(spacing: 8) {
            Button {
                history.copy(entry)
                copied = entry.id
            } label: {
                HStack(spacing: 8) {
                    if let image = history.image(of: entry) {
                        // Big enough to tell which picture it is (user's ask, 2026-11-04).
                        Image(nsImage: image).resizable().aspectRatio(contentMode: .fit)
                            .frame(maxWidth: 120, maxHeight: 64)
                            .clipShape(RoundedRectangle(cornerRadius: 6))
                        Text("picture").foregroundStyle(NotchPalette.secondary)
                    } else {
                        if !entry.files.isEmpty { Image(systemName: "doc").foregroundStyle(NotchPalette.secondary) }
                        Text(entry.text?.replacingOccurrences(of: "\n", with: " ") ?? "").lineLimit(1).truncationMode(.tail)
                    }
                    Spacer()
                    Text(copied == entry.id ? "copied ✓" : entry.at.formatted(.relative(presentation: .named)))
                        .foregroundStyle(NotchPalette.tertiary)
                }
                .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            Button { history.togglePin(entry) } label: {
                Image(systemName: entry.pinned ? "pin.fill" : "pin").foregroundStyle(entry.pinned ? MoodyLook.cream : NotchPalette.tertiary)
            }
            .buttonStyle(.plain)
            .accessibilityLabel(entry.pinned ? "Unpin" : "Pin")
            Button { withAnimation { history.remove(entry) } } label: {
                Image(systemName: "xmark").font(.system(size: 10, weight: .semibold)).foregroundStyle(NotchPalette.tertiary)
            }
            .buttonStyle(.plain)
            .help("Remove this one")
            .accessibilityLabel("Remove from the clipboard history")
        }
        .font(.system(size: 12))
        .padding(.horizontal, 12).padding(.vertical, 4)
        .background(RoundedRectangle(cornerRadius: 10).fill(Color.white.opacity(0.05)))
    }
}

